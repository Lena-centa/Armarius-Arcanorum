/**
 * escapeRegExp — 转义正则特殊字符，防止用户输入直接构造 RegExp(ReDoS 防护)。
 *
 * 所有来自 query 的用户输入在进入 $regex / new RegExp 前必须经此函数。
 *
 * 为什么必要:
 *  - 用户输入可能携带 . * + ? ^ $ { } ( ) | [ ] \ 等元字符,不经转义
 *    直接拼入正则会被解释为模式语法:匹配语义被注入篡改,甚至可构造
 *    出灾难性回溯(ReDoS)模式拖垮网关进程;
 *  - 本网关所有来自 query 的用户输入进入 $regex / new RegExp
 *    (images.controller 的 q / filename 过滤、内存视图复检
 *    memoryMatchesFilter 等)统一经此函数,
 *    保证"用户输入按字面量匹配"的语义;
 *    内部路径前缀转义见 ingest.ts 同字符集本地实现。
 *
 * 转义字符集(正则字符类 [.*+?^${}()|[\]\\] 逐项展开):
 *   . * + ?   —— 元字符(任意字符 / 量词 / 可选)
 *   ^ $       —— 锚点(行首 / 行尾)
 *   { } ( )   —— 量词与分组边界
 *   |         —— 分支符
 *   [ ]       —— 字符类边界
 *   \         —— 转义符本身(优先级最高,放在字符类末尾避免被当作
 *                字符类的转义前缀)
 * 替换为 \\$&:$& 是 JS String.replace 中"本次匹配到的完整子串"占位符,
 * 效果是给每个元字符前插入一个反斜杠,使元字符降级为字面量。
 *
 * 边界条件:
 *  - 空串 / 不含元字符的输入原样返回(无匹配则 replace 不产生替换,
 *    零开销快路径);
 *  - 输入本身已含反斜杠(如 Windows 路径 C:\foo)会被再次转义为
 *    \\ —— 语义是"用户想表达的字符就是反斜杠本身",这正是把输入
 *    当字面量处理的正确行为,而非"输入已经是转义形式";
 *  - 仅处理 ASCII 正则元字符,不做 Unicode 属性转义 / 命名组等处理
 *    (非本函数职责范围)。
 */
export function escapeRegExp(value: string): string {
  // 匹配字符类中的任一元字符,替换为 '\' + 原字符;
  // 字符类内 \] 与 \\ 为转义后的字面量,其余字符保持原样
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
